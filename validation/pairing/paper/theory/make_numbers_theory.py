"""make_numbers_theory.py - the ONLY source of Study 5 numbers in main_theory.tex. Reads results/analysis_study5.json,
results/posthoc_h19_refine.json and the ns-3 raw CSVs (forced-advance counts); writes numbers_theory.tex (macros, each with a comment
naming its source) and tab_h16.tex, tab_h17.tex, tab_stab.tex, tab_x15.tex."""
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAIR = HERE.parents[1]                      # validation/pairing
RES = PAIR / "results"
A = json.loads((RES / "analysis_study5.json").read_text())
PH = json.loads((RES / "posthoc_h19_refine.json").read_text())
MAN = json.loads((RES / "run_manifest_study5.json").read_text())
lines = ["% AUTO-GENERATED by make_numbers_theory.py. Do not edit."]


def d(name, val, src):
    lines.append(f"\\newcommand{{\\{name}}}{{{val}}} % {src}")


f2 = lambda v: f"{v:.2f}"
f3 = lambda v: f"{v:.3f}"
pct0 = lambda v: f"{100 * v:.0f}\\%"
pct1 = lambda v: f"{100 * v:.1f}\\%"
ci2 = lambda c: f"[{c[0]:.2f}, {c[1]:.2f}]"
thou = lambda n: f"{n:,}".replace(",", "{,}")
sci = lambda v: ("0" if v == 0 else f"{v:.1e}".replace("e-0", "e-").replace("e+0", "e+"))

d("FvJobs", thou(MAN["n_jobs"]), "run_manifest_study5 n_jobs")
d("FvJobErr", str(MAN["n_errors"]), "run_manifest_study5 n_errors")
# ---- H16
H = A["H16"]["cells"]
sims = [H[c] for c in ("C1", "C2", "C3", "C4", "C5")]
gens = [H[c] for c in ("G2", "G3")]
d("FvSimRuns", str(sum(c["n_runs"] for c in sims)), "H16 simulator runs")
d("FvGenRuns", str(sum(c["n_runs"] for c in gens)), "H16 generator runs")
d("FvSimPackets", thou(sum(c["total_packets"] for c in sims)), "H16 simulator packets checked")
d("FvGenPackets", thou(sum(c["total_packets"] for c in gens)), "H16 generator packets checked")
mx = max(max(c["max_O1"], c["max_O2"], c["max_O3"], c["max_O4"], c["max_O5"] or 0, c["max_O6_err"]) for c in H.values())
d("FvMaxErr", sci(mx), "H16 max over O1-O6 errors")
d("FvForcedRuns", str(sum(c["n_forced_runs"] for c in H.values())), "H16 runs with forced window advance")
d("FvViol", str(sum(c["O6_violations"] + c["O7_violations"] for c in H.values())), "H16 O6+O7 violations")
d("FvODoublePackets", thou(sum(c["n_O4_packets"] for c in H.values())), "H16 packets checked by truncate-and-rebuild")
d("FvSingleSimMin", pct0(min(c["mean_frac_single_late"] for c in sims)), "H16 min share of blocked packets with exactly one late flow (sim)")
d("FvSingleSimMax", pct0(max(c["mean_frac_single_late"] for c in sims)), "H16 max share (sim)")
d("FvSingleGenA", pct0(H["G2"]["mean_frac_single_late"]), "H16 G2 single-late share")
d("FvSingleGenB", pct0(H["G3"]["mean_frac_single_late"]), "H16 G3 single-late share")
d("FvBlockedSimMin", pct1(min(c["mean_frac_blocked"] for c in sims)), "H16 min blocked share (sim)")
d("FvBlockedSimMax", pct0(max(c["mean_frac_blocked"] for c in sims)), "H16 max blocked share (sim)")
d("FvBlockedGen", pct0(H["G2"]["mean_frac_blocked"]), "H16 G2 blocked share")
cost = A["H16"]["cost_S4_replay_vs_closed"]["A"]
d("FvCostReplay", f2(cost["mean_replay_s"]), "H16 cost: mean seconds for the 15 S4 coalition replays")
d("FvCostClosed", f"{cost['mean_closed_ms']:.1f}", "H16 cost: mean ms for closed-form blame on the full trace")
d("FvCostRatio", f"{cost['mean_replay_s'] * 1000 / cost['mean_closed_ms']:.0f}", "H16 cost ratio replay/closed form (S4)")
ns = []
for p in (PAIR.parent / "ns3" / "results" / "main_campaign" / "main_campaign_raw.csv", RES / "raw_s4_ns3.csv",
          RES / "raw_s3_ns3_nobulk.csv"):
    ns += [float(r["forced_adv_events"]) for r in csv.DictReader(open(p))]
d("FvNsRuns", thou(len(ns)), "ns-3 runs (Mission 1 campaign + Study 3 + Study 4)")
d("FvNsForced", str(sum(v > 0 for v in ns)), "ns-3 runs with forced_adv_events > 0")

# ---- H17
for tag in ("A", "B"):
    c = A["H17"]["cells"][tag]
    d(f"FvRQ{tag}", f2(c["R_Q"]["point"]), f"H17 {tag} R_Q")
    d(f"FvRQ{tag}CI", ci2(c["R_Q"]["ci"]), f"H17 {tag} R_Q ci")
    d(f"FvRX{tag}", f2(c["R_X"]["point"]), f"H17 {tag} R_X")
    d(f"FvRX{tag}CI", ci2(c["R_X"]["ci"]), f"H17 {tag} R_X ci")
    d(f"FvRE{tag}", f2(c["R_e2e"]["point"]), f"H17 {tag} R_e2e")
    d(f"FvShareX{tag}", pct1(c["share_X"]), f"H17 {tag} cross-blocking share of E")
    d(f"FvIdGap{tag}", sci(c["V14_identity_gap"]), f"H17 {tag} V14")
    d(f"FvSig{tag}", str(c["V13_signature_violations"]), f"H17 {tag} V13")
    x = A["H17"]["X9"][tag]
    d(f"FvNineErr{tag}", f2(x["relL1_airport_vs_replayX"]["point"]), f"X9 {tag} relL1 airport vs replay-X Shapley")
    d(f"FvNineErr{tag}CI", ci2(x["relL1_airport_vs_replayX"]["ci"]), f"X9 {tag} ci")
    d(f"FvNineTot{tag}", f3(x["total_airport_over_total_replayX"]), f"X9 {tag} total airport / total replay-X")
    d(f"FvNineE{tag}", f2(x["relL1_airport_vs_replayE2E"]["point"]), f"X9 {tag} relL1 airport vs replay total-delay Shapley")

# ---- H18 / X12 / X13
allst = {**A["H18"]["cells"], **A["X12"]["cells"]}
d("FvBoundViol", str(A["H18"]["bounds_violations"] + A["X12"]["bounds_violations"]), "H18+X12 violations of B1/B2")
d("FvRatioSh", f2(max(v["max_ratio_shapley"] for v in allst.values())), "X13 max Shapley ratio")
d("FvRatioRel", f"{max(v['max_ratio_releaser'] for v in allst.values()):.0f}", "X13 max releaser ratio")
d("FvStabTies", str(sum(1 for k, v in allst.items() if k[0] == "C" and v["diff_rel_minus_sh"]["point"] == 0.0)),
  "stability cells with identical Shapley/releaser change")
d("FvStabCells", str(sum(1 for k in allst if k[0] == "C")), "stability simulator cell-levels")
g2 = allst["G2/eps0.1"]
d("FvStabGtwoSh", f3(g2["mean_Dsh"]), "X12 G2 eps0.1 mean Shapley change")
d("FvStabGtwoRel", f3(g2["mean_Drel"]), "X12 G2 eps0.1 mean releaser change")

# ---- H19
h = A["H19"]
d("FvNQuant", str(h["n_quantities"]), "H19 number of closed-form quantities")
d("FvMaxZ", f2(h["max_abs_z"]), "H19 max |z|")
d("FvEffGap", sci(h["efficiency_max_rel_gap"]), "H19 efficiency gap")
d("FvQuadMax", sci(h["quadrature_doubling_max_rel_change"]), "H19 quadrature doubling max rel change")
d("FvRefZP", f2(PH["P6"]["max_abs_z_refined"]), "post hoc P6 refined max |z|")
d("FvRefZS", f2(PH["P7"]["max_abs_z_refined"]), "post hoc P7 refined max |z|")
d("FvRefDriftS", sci(PH["P7"]["max_rel_change_80k_vs_320k"]), "post hoc P7 convergence 80k vs 320k")
d("FvRefDriftP", sci(PH["P6"]["max_rel_change_80k_vs_320k"]), "post hoc P6 convergence 80k vs 320k")

# ---- X15
for tag, cell in (("A", "X1"), ("B", "X2"), ("C", "X3")):
    c = A["X15"][cell]
    d(f"FvPred{tag}", f2(c["cell_pred_over_obs"]["point"]), f"X15 {cell} predicted/observed cross-blocking")
    d(f"FvPred{tag}CI", ci2(c["cell_pred_over_obs"]["ci"]), f"X15 {cell} ci")
    d(f"FvPredErr{tag}", f2(c["blame_relL1_error"]["point"]), f"X15 {cell} blame relL1 error")
    d(f"FvPredObs{tag}", f3(c["mean_obs_cross_blocking_ms"]), f"X15 {cell} observed mean cross-blocking ms")

# ---- Study 6 (windows, timers, ns-3 second implementation); optional until analysis_study6.json exists
S6P = RES / "analysis_study6.json"
if S6P.exists():
    S6 = json.loads(S6P.read_text())
    G, Nn, Dd = S6["G4"], S6["NS3"], S6["D2"]
    gt = G["totals"]
    d("FvSxTraces", str(gt["n_traces"]), "S6 G4 traces")
    d("FvSxPackets", thou(gt["n_packets"]), "S6 G4 packets checked")
    d("FvSxEvents", thou(gt["total_events"]), "S6 G4 forced events (window advances + timeouts)")
    d("FvSxEventShare", pct1(gt["frac_traces_with_event"]), "S6 G4 share of traces with >= 1 forced event")
    d("FvSxErr", sci(gt["max_error_O1_O6"]), "S6 G4 max error O1-O6")
    d("FvSxMis", str(sum(c["set_mismatch"] for c in G["cells"].values())), "S6 G4 delivered-set mismatches")
    d("FvSxViol", str(sum(c["O6_viol"] + c["O7_viol"] for c in G["cells"].values())), "S6 G4 O6+O7 violations")
    d("FvSxCert", pct0(gt["certified_share_overall"]), "S6 G4 certified share of delivered packets")
    d("FvSxCertRef", pct0(1 - gt["certified_share_overall"]), "S6 G4 share of delivered packets NOT certified")
    d("FvSxFalse", str(sum(c["false_rejections"] for c in G["cells"].values())), "S6 G4 false rejections")
    d("FvSxSkipCert", thou(gt["skipped_but_certified"]), "S6 G4 packets certified although a slot was skipped")
    d("FvSxTenRatio", f2(gt["T10_max_ratio"]), "S6 G4 max (phi change)/(T10 bound)")
    d("FvSxTenViol", str(sum(c["T10_l_viol"] + c["T10_phi_viol"] for c in G["cells"].values())), "S6 G4 T10 violations")
    sk = [c["blocked_from_skipped"] for c in G["cells"].values() if c["blocked_from_skipped"] == c["blocked_from_skipped"]]
    d("FvSxSkipMin", pct0(min(sk)), "S6 G4 min share of blocked packets whose largest lateness is a skipped slot")
    d("FvSxSkipMax", pct0(max(sk)), "S6 G4 max share")
    d("FvNsSixRuns", str(Nn["n_runs"]), "S6 ns-3 runs")
    d("FvNsSixExcl", str(Nn["n_excluded_forced"]), "S6 ns-3 runs excluded (forced advance)")
    d("FvNsSixPackets", thou(Nn["n_packets_checked"]), "S6 ns-3 packets checked")
    d("FvNsSixBlocked", thou(Nn["n_blocked_packets"]), "S6 ns-3 blocked packets")
    d("FvNsSixErr", sci(Nn["N1_max_err"]), "S6 ns-3 release-law max error (ms)")
    d("FvNsSixViol", str(Nn["N1_viol"]), "S6 ns-3 release-law violations")
    d("FvNsSixPy", sci(Nn["py_max_err"]), "S6 ns-3 Python-receiver vs ns-3 release max error (ms)")
    d("FvNsSixPyMis", str(Nn["py_mismatch"]), "S6 ns-3 Python-receiver release mismatches")
    d("FvNsSixOr", sci(max(Nn["O2"], Nn["O3"], Nn["O4"], Nn["O6_err"])), "S6 ns-3 oracle max error O2-O6")
    d("FvNsSixHc", sci(Nn["H24_max_diff_cross"]), "S6 ns-3 H24 max |trace cross - csv cross|")
    d("FvNsSixHw", sci(Nn["H24_max_diff_within"]), "S6 ns-3 H24 max |trace within - csv within|")
    d("FvNsSixOcc", f"{Nn['X16_equal_runs']}/{Nn['n_runs'] - Nn['n_excluded_forced']}", "S6 ns-3 X16 runs with equal max occupancy")
    ml = [v["multi_late_share"] for v in Nn["by_cell"].values()]
    d("FvNsSixMultiMin", pct1(min(ml)), "S6 ns-3 min multi-late share of blocked packets")
    d("FvNsSixMultiMax", pct1(max(ml)), "S6 ns-3 max multi-late share")
    d("FvDtwoRatioAll", pct1(Dd["overall_ratio_X_over_ns3cross"]), "S6 D2 overall X / ns-3-style cross")
    d("FvDtwoRatioMin", pct1(Dd["min_cell_ratio"]), "S6 D2 min cell ratio")
    d("FvDtwoSX", f3(Dd["overall_S_over_X"]), "S6 D2 S / X")
    t = ["% AUTO-GENERATED", "\\begin{tabular}{lrrrrr}", "\\toprule",
         "$(W,\\tau,p_{\\rm loss})$ & traces & forced events/trace & delivered & blocked from skipped slot & certified\\\\", "\\midrule"]
    for k, c in G["cells"].items():
        W_, tau_, pl_ = k.split("_")
        W_ = W_[1:]
        tau_ = tau_[3:]
        pl_ = pl_[4:]
        t.append(f"({W_}, {tau_}, {pl_}) & {c['n_traces']} & {c['forced_events_mean']:.1f} & {pct0(c['delivered_share'])} & "
                 f"{pct0(c['blocked_from_skipped']) if c['blocked_from_skipped'] == c['blocked_from_skipped'] else '--'} & {pct0(c['certified_share'])}\\\\")
    t += ["\\bottomrule", "\\end{tabular}"]
    (HERE / "tab_s6g4.tex").write_text("\n".join(t) + "\n")
    t = ["% AUTO-GENERATED", "\\begin{tabular}{lrrrr}", "\\toprule",
         "cell & $\\bar X$ (ms) & $\\bar S$ (ms) & ns-3 cross wait (ms) & $\\bar X$ / ns-3 cross\\\\", "\\midrule"]
    for k, v in Dd["cells"].items():
        r_ = v["ratio_X_over_ns3cross"]
        t.append(f"{k.replace('/', ' / ')} & {v['mean_X_ms']:.3f} & {v['mean_S_ms']:.3f} & {v['mean_ns3cross_ms']:.3f} & "
                 f"{pct1(r_['point']) if r_['point'] is not None else '--'}\\\\")
    t += ["\\bottomrule", "\\end{tabular}"]
    (HERE / "tab_s6d2.tex").write_text("\n".join(t) + "\n")

(HERE / "numbers_theory.tex").write_text("\n".join(lines) + "\n")

# ---- tables
names = {"C1": "S4 FIFO (1.0, 0.1)", "C2": "S4 FullSASP (1.0, 0.1)", "C3": "S4 FIFO (0.75, 3.0)", "C4": "S8 FIFO (1.0, 0.1)",
         "C5": "S8 FIFO (1.0, 3.0)", "G2": "G2 multiplexed streams", "G3": "G3 heavy-tailed paths"}
t = ["% AUTO-GENERATED", "\\begin{tabular}{lrrrrrr}", "\\toprule",
     "cell & runs & packets & blocked & one late flow & forced adv. & max error\\\\", "\\midrule"]
for k, nm in names.items():
    c = H[k]
    e = max(c["max_O1"], c["max_O2"], c["max_O3"], c["max_O4"], c["max_O5"] or 0, c["max_O6_err"])
    t.append(f"{nm} & {c['n_runs']} & {thou(c['total_packets'])} & {pct1(c['mean_frac_blocked'])} & "
             f"{pct0(c['mean_frac_single_late'])} & {c['n_forced_runs']} & {sci(e)}\\\\")
t += ["\\bottomrule", "\\end{tabular}"]
(HERE / "tab_h16.tex").write_text("\n".join(t) + "\n")

t = ["% AUTO-GENERATED", "\\begin{tabular}{lrrrr}", "\\toprule",
     "cell & cross share of $E$ & $R_Q$ & $R_X$ (replay) & $R$ (total)\\\\", "\\midrule"]
for cell, nm in (("A", "S4 FIFO (1.0, 0.1)"), ("B", "S4 FIFO (0.75, 3.0)")):
    c = A["H17"]["cells"][cell]
    t.append(f"{nm} & {pct1(c['share_X'])} & {f2(c['R_Q']['point'])} {ci2(c['R_Q']['ci'])} & "
             f"{f2(c['R_X']['point'])} {ci2(c['R_X']['ci'])} & {f2(c['R_e2e']['point'])}\\\\")
t += ["\\bottomrule", "\\end{tabular}"]
(HERE / "tab_h17.tex").write_text("\n".join(t) + "\n")

t = ["% AUTO-GENERATED", "\\begin{tabular}{lrrrrr}", "\\toprule",
     "cell, $\\epsilon$ (ms) & packets & mean change Shapley & mean change releaser & max ratio Shapley & max ratio releaser\\\\",
     "\\midrule"]
for k, v in allst.items():
    cell, e = k.split("/eps")
    if cell in ("C1", "C2", "C3") and e != "0.1":
        continue
    t.append(f"{cell}, {e} & {v['n_packets']} & {f3(v['mean_Dsh'])} & {f3(v['mean_Drel'])} & {f2(v['max_ratio_shapley'])} & "
             f"{v['max_ratio_releaser']:.1f}\\\\")
t += ["\\bottomrule", "\\end{tabular}"]
(HERE / "tab_stab.tex").write_text("\n".join(t) + "\n")

t = ["% AUTO-GENERATED", "\\begin{tabular}{lrrrr}", "\\toprule",
     "cell (load, $\\Delta\\mu$) & observed $\\bar X$ (ms) & predicted / observed & interval & blame L1 error\\\\", "\\midrule"]
for cell, nm in (("X1", "(0.1, 2.0)"), ("X2", "(0.25, 2.0)"), ("X3", "(0.5, 3.0)")):
    c = A["X15"][cell]
    t.append(f"{nm} & {f3(c['mean_obs_cross_blocking_ms'])} & {f2(c['cell_pred_over_obs']['point'])} & "
             f"{ci2(c['cell_pred_over_obs']['ci'])} & {f2(c['blame_relL1_error']['point'])}\\\\")
t += ["\\bottomrule", "\\end{tabular}"]
(HERE / "tab_x15.tex").write_text("\n".join(t) + "\n")
print(f"wrote numbers_theory.tex ({len(lines) - 1} macros) and 4 tables")
