#!/usr/bin/env python3
"""make_paper_tables.py - writes paper/ns3_tables.tex from results/analysis/*.csv (no hand-typed numbers)."""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
A = HERE / "results" / "analysis"
OUT = HERE.parent.parent / "paper" / "ns3_tables.tex"
means = {(r["campaign"], r["cond"], r["load"], r["arm"]): r for r in csv.DictReader(open(A / "arm_means.csv"))}
comps = list(csv.DictReader(open(A / "comparisons.csv")))
f = lambda x, d=3: f"{float(x):.{d}f}"  # noqa: E731


def comp(campaign, fam, cond, load):
    return next(r for r in comps if (r["campaign"], r["family"], r["cond"], r["load"]) == (campaign, fam, cond, load))


def pfmt(p):
    p = float(p)
    return "$<\\!10^{-3}$" if p < 1e-3 else f"{p:.3f}"


L = []
L.append("% AUTO-GENERATED by validation/ns3/make_paper_tables.py - do not edit by hand")
L.append("\\begin{table*}[t]\\centering\\footnotesize")
L.append("\\caption{ns-3.47 main campaign (30 seeds per cell and arm). Primary endpoint: mean cross-flow reorder wait of "
         "latency-sensitive (LS) packets (ms). Secondary: LS p99 one-way delay (ms), relative change of Full SASP vs FIFO and "
         "Holm-adjusted $p$ (family F6). Asymmetry A0/A1/A2 = measured median completion-time ratio 1.00/1.42/2.96; "
         "load L0/L1/L2 = 0.30/0.60/0.85 of the measured capacity.}\\label{tab:ns3main}")
L.append("\\begin{tabular}{llrrrrrrrr}\\toprule")
L.append("Asym. & Load & \\multicolumn{3}{c}{Cross wait (ms)} & \\multicolumn{3}{c}{LS p99 delay (ms)} & $\\Delta$p99 & $p_{\\text{Holm}}$\\\\")
L.append("& & FIFO & Mean-Only & Full & FIFO & Mean-Only & Full & Full vs FIFO & \\\\\\midrule")
for cond in ("A0", "A1", "A2"):
    for load in ("L0", "L1", "L2"):
        g = lambda arm, k: means[("main", cond, load, arm)][k + "_mean"]  # noqa: E731
        c = comp("main", "F6", cond, load)
        L.append(f"{cond} & {load} & {f(g('FIFO','cross_wait_ms'),4)} & {f(g('MeanOnly','cross_wait_ms'),4)} & "
                 f"{f(g('FullSASP','cross_wait_ms'),4)} & {f(g('FIFO','ls_delay_p99_ms'))} & {f(g('MeanOnly','ls_delay_p99_ms'))} & "
                 f"{f(g('FullSASP','ls_delay_p99_ms'))} & {float(c['rel_reduction_pct']):+.1f}\\% & {pfmt(c['p_holm'])}\\\\")
L.append("\\bottomrule\\end{tabular}\\end{table*}")

L.append("\\begin{table*}[t]\\centering\\footnotesize")
L.append("\\caption{ns-3.47 variance/priority ablation (load L2, 30 seeds per cell and arm). Cross wait in ms. "
         "V1/V2/V4 = measured per-link completion-variance ratios 1.01/1.29/2.32 at this load (targets 1/2/4); "
         "$w$ = priority weight ratio $w_{\\text{LS}}/w_{\\text{bulk}}$. Last columns: Full vs Mean-Only (family F4, Holm).}\\label{tab:ns3abl}")
L.append("\\begin{tabular}{llrrrrrr}\\toprule")
L.append("Regime & $w$ & FIFO & Mean-Only & Full & Mean vs FIFO & Full vs Mean & $p_{\\text{Holm}}$\\\\\\midrule")
for reg in ("V1", "V2", "V4"):
    for w in (1, 10, 50):
        cell = f"{reg}_w{w}"
        g = lambda arm, k: means[("ablation", cell, "L2", arm)][k + "_mean"]  # noqa: E731
        c4 = comp("ablation", "F4", cell, "L2")
        d1 = comp("ablation", "D1", cell, "L2")
        L.append(f"{reg} & {w} & {f(g('FIFO','cross_wait_ms'),4)} & {f(g('MeanOnly','cross_wait_ms'),4)} & "
                 f"{f(g('FullSASP','cross_wait_ms'),4)} & {float(d1['rel_reduction_pct']):+.1f}\\% & "
                 f"{float(c4['rel_reduction_pct']):+.1f}\\% & {pfmt(c4['p_holm'])}\\\\")
L.append("\\bottomrule\\end{tabular}\\end{table*}")
OUT.write_text("\n".join(L) + "\n")
print("wrote", OUT)
